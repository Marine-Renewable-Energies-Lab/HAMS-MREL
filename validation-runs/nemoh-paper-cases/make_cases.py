def oc4_polygons(hull):
    """The waterline loops of the OC4 hull as counter-clockwise polygons of its waterline nodes, main column first, then
    the offset columns in the order of make_mesh.OC4_OFFSET_AXES (what oc4_free_surface needs)."""
    edges = []
    for p in hull.panels:
        top = [i for i in p if abs(hull.nodes[i - 1][2]) < nemoh_mesh.Z0]
        if len(top) >= 2:
            edges.append(top[:2])
    order = [(0.0, 0.0)] + list(make_mesh.OC4_OFFSET_AXES)
    polys = [[] for _ in order]
    seen = set()
    for a, b in edges:
        for v in (a, b):
            if v in seen:
                continue
            seen.add(v)
            x, y, _ = hull.nodes[v - 1]
            k = min(range(len(order)), key=lambda j: math.hypot(x - order[j][0], y - order[j][1]))
            polys[k].append((x, y))
    out = []
    for (cx, cy), pts in zip(order, polys):
        pts.sort(key=lambda q: math.atan2(q[1] - cy, q[0] - cx))
        out.append(pts)
    return out


