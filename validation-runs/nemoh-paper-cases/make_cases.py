"""Write the HAMS-MREL (and Nemoh v3.0.3) inputs of the validation cases of Kurnia and Ducrozet (2023), and of the OC3
Hywind and cylinder test cases (11 and 8b) of Nemoh v3.0.3.

Usage: python -I make_cases.py NEMOH_TESTCASES OUT_DIR

NEMOH_TESTCASES is the TestCases folder of Nemoh v3.0.3 (GPL; only its documented input files are read: meshes,
Nemoh.cal, Mesh.cal, Mechanics/*.dat). OUT_DIR receives one folder per case, <case>/input, outside the repository, and
cases.json with the facts the cost estimate and the report need. Nothing here runs HAMS or Nemoh.

Conventions.
- HAMS has rho = 1000 kg/m^3 and g = 9.80665 m/s^2 built in; Nemoh's cases and HydroStar use 1025 and 9.81. The mass
  and inertia are scaled by 1000/1025 and the stiffness by (1000 x 9.80665)/(1025 x 9.81), so the non-dimensional
  problem is the same; HAMS's outputs are non-dimensional (rho g A^2 ...), and the comparison divides the reference by
  its own rho g. The wave number differs by g: 3.4e-4 relative at a given omega [derived].
- Meshes keep Nemoh's vertex order (Nemoh: normal into the fluid; HAMS takes the opposite normal from the same order).
- The lids shipped with the Nemoh meshes put lid centroids 0.08 to 0.46 m from the hull wall, 0.07 to 0.18 of the
  waterline panel row; input_files.md asks for 0.3 to 0.5. So each case gets a HAMS lid: rings on the waterline circle,
  ring width about the waterline row height (lid_disc); a single fan on a column narrower than about 1.5 rows.
- The rotation centre of each case is Nemoh's (and HydroStar's COORD) point.
"""
