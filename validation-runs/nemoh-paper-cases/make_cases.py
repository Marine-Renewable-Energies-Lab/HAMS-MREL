RHO_N, G_N = 1025.0, 9.81
RHO_H, G_H = make_mesh.RHO, make_mesh.G
MASS_SCALE = RHO_H / RHO_N
STIFF_SCALE = RHO_H * G_H / (RHO_N * G_N)
DW = 0.0628   # rad/s, the grid of the Nemoh cases and the HydroStar files (2 pi / 100, rounded as there)


def grid(n, step=DW, first=None):
    first = step if first is None else first
    return [round(first + k * step, 6) for k in range(n)]


# ---------------------------------------------------------------------------------------------------------------- files
def write_control(path, depth, freqs, headings, centre, irsp, threads=24, note=""):
    with open(path, "w") as f:
        f.write("   --------------HAMS Control file---------------\n\n")
        f.write("   Waterdepth  %sD0\n\n" % ("%.1f" % depth))
        f.write("   #Start Definition of Wave Frequencies\n")
        f.write("    0_inf_frequency_limits      0\n")
        f.write("    Input_frequency_type        3\n")
        f.write("    Output_frequency_type       3\n")
        f.write("    Number_of_frequencies%7d\n" % len(freqs))
        f.write(" " + " ".join("%.4f" % w for w in freqs) + "\n")
        f.write("   #End Definition of Wave Frequencies\n\n")
        f.write("   #Start Definition of Wave Headings\n")
        f.write("    Number_of_headings%10d\n" % len(headings))
        f.write(" " + " ".join("%.4f" % b for b in headings) + "\n")
        f.write("   #End Definition of Wave Headings\n\n")
        f.write("    Reference_body_center   %12.3f%12.3f%12.3f\n" % tuple(centre))
        f.write("    Reference_body_length   1.0D0\n")
        f.write("    Wave_diffrac_solution    1\n")
        f.write("    If_remove_irr_freq       %d\n" % irsp)
        f.write("    Number of threads       %d\n\n" % threads)
        f.write("   #Start Definition of Pressure and/or Elevation (PE)\n")
        f.write("    Number_of_field_points     0\n")
        f.write("   #End Definition of Pressure and/or Elevation\n\n")
        f.write("   ----------End HAMS Control file---------------\n\n")
        f.write("   Note: generated by validation-runs/nemoh-paper-cases/make_cases.py. %s\n" % note)


def write_hydrostatic(path, cg, mass, restoring, external=None):
    zero = [[0.0] * 6 for _ in range(6)]
    with open(path, "w") as f:
        f.write(" Center of Gravity:\n")
        f.write("  %.12E  %.12E  %.12E\n" % tuple(cg))
        for title, m in (("Body Mass Matrix", mass), ("External Linear Damping Matrix", zero),
                         ("External Quadratic Damping Matrix", zero), ("Hydrostatic Restoring Matrix", restoring),
                         ("External Restoring Matrix", external or zero)):
            f.write(" %s:\n" % title)
            make_mesh.write_matrix(f, m)


def write_second_order(path, lines, note):
    with open(path, "w") as f:
        f.write("! %s\n" % note)
        for line in lines:
            f.write(line + "\n")


def read_matrix(path):
    with open(path) as f:
        rows = [[float(v) for v in ln.split()] for ln in f if ln.strip()]
    if len(rows) != 6 or any(len(r) != 6 for r in rows):
        raise ValueError("%s is not a 6 x 6 matrix" % path)
    return rows


def scaled(m, s):
    return [[v * s for v in row] for row in m]


# ---------------------------------------------------------------------------------------------------------------- lids
def waterline_loops(hull, half=False):
    """Loops of the hull's z = 0 nodes, grouped by connectivity of the waterline edges: list of (cx, cy, radius, nnodes)
    of the best-fit circle of each loop (centre = mean of its nodes)."""
    edges = []
    for p in hull.panels:
        pts = [hull.nodes[i - 1] for i in p]
        top = [i for i in p if abs(hull.nodes[i - 1][2]) < nemoh_mesh.Z0]
        if len(top) >= 2:
            edges.append((top[0], top[1]))
    parent = {}

    def find(a):
        while parent.setdefault(a, a) != a:
            a = parent[a]
        return a
    for a, b in edges:
        parent[find(a)] = find(b)
    groups = {}
    for a, b in edges:
        for v in (a, b):
            groups.setdefault(find(v), set()).add(v)
    out = []
    for nodes in groups.values():
        xs = [hull.nodes[i - 1][0] for i in nodes]
        ys = [hull.nodes[i - 1][1] for i in nodes]
        cx, cy = sum(xs) / len(xs), sum(ys) / len(ys)
        if half:
            cx, cy = 0.5 * (max(xs) + min(xs)), 0.0
        rs = [math.hypot(x - cx, y - cy) for x, y in zip(xs, ys)]
        out.append((cx, cy, sum(rs) / len(rs), len(nodes), max(rs) - min(rs)))
    return out


def lid_disc(cx, cy, radius, n_outer, row, half=False):
    """Lid of a circular waterline: rings of width about row from the waterline circle inwards (the first ring's
    centroids about row/2 from the wall), ring_counts halving, a fan at the centre; normals -z. half: keep y > 0
    (for ISY = 1, the hull's half), which needs cy = 0 and an even n_outer."""
    nr = max(1, int(round(radius / row)))   # one ring (a fan) on a column narrower than about 1.5 rows
    radii = [radius * (1.0 - i / nr) for i in range(nr + 1)]
    n = n_outer + (n_outer % 2)
    mesh = make_mesh.Mesh()
    make_mesh._disc(mesh, cx, cy, radii, make_mesh.ring_counts(radii, n), 0.0, up=False)
    if half:
        if abs(cy) > 1e-9:
            raise ValueError("a half lid must be centred on y = 0")
        mesh = make_mesh.half_in_y(mesh)
    return mesh


def lid_for(hull, row, half=False):
    lid = make_mesh.Mesh()
    loops = waterline_loops(hull, half)
    for cx, cy, r, n, spread in loops:
        if spread > 0.02 * r:
            raise ValueError("waterline loop at (%.2f, %.2f) is not a circle (spread %.3f m)" % (cx, cy, spread))
        if half:
            n = 2 * (n - 1)  # nodes of the half circle including both ends on y = 0
            cy = 0.0
        part = lid_disc(cx, cy, r, n, row, half)
        for p in part.panels:
            lid.add_panel([part.nodes[i - 1] for i in p])
    clear, wl_row = nemoh_mesh.waterline_clearance(hull, lid)
    return lid, dict(loops=[dict(cx=round(c[0], 3), cy=round(c[1], 3), r=round(c[2], 4), n=c[3]) for c in loops],
                     panels=len(lid.panels), clearance=round(clear, 4), wl_row=round(wl_row, 4),
                     ratio=round(clear / wl_row, 3))


# ---------------------------------------------------------------------------------------------------------------- C, F
def median_panel(mesh):
    sizes = []
    for p in mesh.panels:
        pts = [mesh.nodes[i - 1] for i in p]
        area = 0.0
        for k in range(1, len(pts) - 1):
            c = make_mesh.cross(make_mesh.sub(pts[k], pts[0]), make_mesh.sub(pts[k + 1], pts[0]))
            area += 0.5 * math.sqrt(sum(v * v for v in c))
        sizes.append(math.sqrt(area))
    sizes.sort()
    n = len(sizes)
    return sizes[(n - 1) // 2] if n % 2 else 0.5 * (sizes[n // 2 - 1] + sizes[n // 2])


def generated_cs_points(hull, depth, half=False):
    """Number of points of the generated cylinder C and its F (cs_shape = cylinder, default cs_* keys), as
    ControlSurfaceMesh.f90 builds them: one point per C panel and per Gamma_c segment, one per F panel. For the cost
    estimate only."""
    full = nemoh_mesh.mirrored(hull) if half else hull
    med = median_panel(full)
    xs = [n[0] for n in full.nodes]
    ys = [n[1] for n in full.nodes]
    cx, cy = 0.5 * (max(xs) + min(xs)), 0.5 * (max(ys) + min(ys))
    radius = max(math.hypot(n[0] - cx, n[1] - cy) for n in full.nodes) + 4.0 * med
    zmin = min(n[2] for n in full.nodes)
    dd = min(-zmin + 4.0 * med, depth)
    bottom = -zmin + 4.0 * med < depth
    # wall_levels
    t1, tk, cum, nrow = 0.5 * med, min(med, 0.5 * med * 1.25), 0.5 * med, 1
    while cum + 0.5 * tk < dd:
        nrow, cum, tk = nrow + 1, cum + tk, min(med, tk * 1.25)
    npt = max(8, int(math.ceil(2.0 * math.pi * radius / med)))
    nr = max(1, int(math.ceil(radius / med)))
    c_panels = npt * nrow + (npt * nr if bottom else 0)
    loops = waterline_loops(full)
    nwl = sum(n for _, _, _, n, _ in loops)
    rwl = sum(r for _, _, r, _, _ in loops) / len(loops)
    rows = max(2, int(round((radius - rwl) / med)))
    return dict(median_panel=round(med, 3), c_radius=round(radius, 2), c_panels=c_panels, gamma=npt,
                f_panels=nwl * rows, points=c_panels + npt + nwl * rows)


# ---------------------------------------------------------------------------------------------------------------- cases
def write_hams_case(root, name, hull, lid, isy, control, hydro, second=None, extra=None):
    folder = os.path.join(root, name, "input")
    os.makedirs(folder, exist_ok=True)
    make_mesh.write_mesh(os.path.join(folder, "HullMesh.pnl"), hull, isy)
    if lid is not None:
        make_mesh.write_mesh(os.path.join(folder, "WaterPlaneMesh.pnl"), lid, isy, title="Waterplane Mesh File")
    write_control(os.path.join(folder, "ControlFile.in"), **control)
    if hydro is not None:
        write_hydrostatic(os.path.join(folder, "Hydrostatic.in"), **hydro)
    if second is not None:
        write_second_order(os.path.join(folder, "SecondOrder.in"), second, "make_cases.py, case " + name)
    for fname, mesh in (extra or {}).items():
        make_mesh.write_mesh(os.path.join(folder, fname), mesh,
                             title="Free Surface Mesh File" if fname.startswith("FS") else "Hull Mesh File")
    return folder


def nemoh_hydro(mech, cg):
    return dict(cg=cg, mass=scaled(read_matrix(os.path.join(mech, "Inertia.dat")), MASS_SCALE),
                restoring=scaled(read_matrix(os.path.join(mech, "Kh.dat")), STIFF_SCALE),
                external=scaled(read_matrix(os.path.join(mech, "Km.dat")), STIFF_SCALE))


def diff_keys(mean_drift=1):
    return ["mean_drift = %d" % mean_drift, "drift_methods = far near", "motion_state = free",
            "velocity_method = differencing", "waterline_method = extrapolate", "write_terms = 1",
            "qtf = 1", "qtf_terms = body", "qtf_max_dw = 0"]


def heave_plate(radius=10.0, draft=10.0, plate_radius=15.0, thickness=0.1, ntheta=96, nz=12, nr_plate=6, nr_bottom=10):
    """Truncated cylinder (radius, draft) with a thin heave plate at its bottom: column wall from z = 0 to
    -(draft - thickness), plate top annulus at -(draft - thickness) from radius to plate_radius, plate rim, plate bottom
    disc at -draft. The plate position (its bottom at the draft) is assumed: Kurnia and Ducrozet (2023) give the draft,
    the plate radius and thickness only. Rows are cosine spaced (finer at the corners); the bottom disc rings halve
    towards the centre (no slivers at the centre, the problem the paper had with an axisymmetric mesh)."""
    out = make_mesh.Mesh()
    top = draft - thickness
    make_mesh._wall(out, 0.0, 0.0, radius, ntheta, make_mesh._cosine(0.0, -top, nz))
    radii = make_mesh._cosine(plate_radius, radius, nr_plate)
    make_mesh._disc(out, 0.0, 0.0, radii, [ntheta] * len(radii), -top, up=False)
    make_mesh._wall(out, 0.0, 0.0, plate_radius, ntheta, [-top, -draft])
    radii = [plate_radius * math.cos(0.5 * math.pi * i / nr_bottom) for i in range(nr_bottom + 1)]
    radii[-1] = 0.0
    make_mesh._disc(out, 0.0, 0.0, radii, make_mesh.ring_counts(radii, ntheta), -draft, up=True)
    return out


def graded(a, b, h0, growth=1.25, hmax=1.0):
    """Levels from a to b (either order), the first step h0 next to a, each next step growth times larger up to hmax,
    then scaled so that the last level is b."""
    d = abs(b - a)
    steps, h = [], h0
    while sum(steps) + 0.5 * h < d:
        steps.append(h)
        h = min(hmax, h * growth)
    steps = [x * d / sum(steps) for x in steps]
    out, x = [a], a
    for st in steps:
        x += st if b > a else -st
        out.append(x)
    out[-1] = b
    return out


def heave_plate_fine(radius=10.0, draft=10.0, plate_radius=15.0, thickness=0.1, n_plate=320, n_col=160, nz=20, h_edge=0.2,
                     h_max=0.8):
    """As heave_plate, refined on the plate: n_plate nodes around the plate edge (arc 0.29 m for 320), rows of h_edge next to
    the plate edge on its top and bottom and next to the column on the top annulus, growing by 1.25 to h_max. The top
    annulus halves its count from n_plate to n_col (the column's) half-way in, so the column wall stays conforming; the
    bottom disc halves inwards as ring_counts decides."""
    if n_plate != 2 * n_col:
        raise ValueError("the plate needs twice the nodes of the column")
    out = make_mesh.Mesh()
    top = draft - thickness
    make_mesh._wall(out, 0.0, 0.0, radius, n_col, make_mesh._cosine(0.0, -top, nz))
    mid = 0.5 * (radius + plate_radius)
    outer = graded(plate_radius, mid, h_edge, hmax=h_max)
    inner = [mid] + [r for r in graded(radius, mid, h_edge, hmax=h_max)[::-1][1:]]
    radii = outer + inner[1:]
    counts = [n_plate] * len(outer) + [n_col] * (len(inner) - 1)
    make_mesh._disc(out, 0.0, 0.0, radii, counts, -top, up=False)
    make_mesh._wall(out, 0.0, 0.0, plate_radius, n_plate, [-top, -draft])
    radii = graded(plate_radius, 0.0, h_edge, hmax=1.0)
    make_mesh._disc(out, 0.0, 0.0, radii, make_mesh.ring_counts(radii, n_plate), -draft, up=True)
    return out


